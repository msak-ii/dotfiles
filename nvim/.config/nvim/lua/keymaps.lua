vim.keymap.set('n', '<Leader>x', '<Cmd>luafile .nvim.lua<Cr>', { desc = 'exrc' })
vim.keymap.set('n', '<Leader>yh', function()
  y2cb('%:h')
end, { desc = 'directory' })
vim.keymap.set('n', '<Leader>yp', function()
  y2cb('%')
end, { desc = 'filepath' })
vim.keymap.set('n', '<Leader>yt', function()
  y2cb('%:t')
end, { desc = 'filename' })
